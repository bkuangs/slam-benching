"""Non-repeating regolith MDL material for OmniLRS terrains (LargeScale clipmaps), pure Python (no Isaac imports).

`mdl_text()` writes a self-contained MDL module that replaces OmniPBR's single UV-tiled lookup of the LunarRegolith8k
textures (period 1/texture_scale = 2 m, visible as a grid from 30-60 m altitude) with:

* world-space projection: the lookup coordinates come from the world-space shading position (plus `offset_xy`, the
  LargeScale starting_position, so the pattern is fixed to global DEM coordinates), not from the mesh UVs. It does not
  slide when the clipmap mesh is re-centred, whatever update_every_n_meters is.
* texture bombing: a square lattice of cells (`cell_m`); every lattice point gets a hashed random rotation and texture
  offset, and the 4 lattice points around a shading point are blended with smoothstep bilinear weights. The blend is
  variance-preserving (Heitz & Neyret 2018: mean + sum w_i (T_i - mean) / sqrt(sum w_i^2)), so it does not wash out
  the texture contrast between lattice points. The tangent-space normal of each sample is rotated back to world xy.
* large-scale albedo variation: multi-octave value noise over world xy (wavelengths `bright_wavelengths_m`), scaled so
  that its standard deviation is `bright_amp`/2 (i.e. +-bright_amp ~ 2 sigma), clamped to +-1.5 bright_amp.

The BSDF is Lambertian (OmniPBR with roughness 1 and no metal is nearly so). `fbm_np()` mirrors the MDL noise in numpy
(same hash and octaves) to calibrate the normalization and for tests.
"""
import numpy as np

TEX_DIR = "./LunarRegolith8k"
# LunarRegolith8k statistics (sRGB-decoded diffuse, 16-bit AO), measured on the 8k textures (4x subsampled)
DIFF_MEAN_LIN = (0.1578, 0.1344, 0.1258)
AO_MEAN = 0.9088
WRAP = 1024.0  # lattice indices are wrapped to [0, WRAP) before hashing (keeps sin() arguments small)
OCTAVE_GAIN = 0.7


def _frac(x):
    return x - np.floor(x)


def hash_np(ix, iy, seed=0.0):
    """numpy mirror of the MDL hash1(): uniform [0, 1) per (wrapped) integer lattice point."""
    ix = ix - WRAP * np.floor(ix / WRAP)
    iy = iy - WRAP * np.floor(iy / WRAP)
    return _frac(np.sin(ix * 127.1 + iy * 311.7 + seed * 74.7) * 43758.5453)


def value_noise_np(x, y, seed=0.0):
    ix, iy = np.floor(x), np.floor(y)
    fx, fy = x - ix, y - iy
    fx, fy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
    a, b = hash_np(ix, iy, seed), hash_np(ix + 1, iy, seed)
    c, d = hash_np(ix, iy + 1, seed), hash_np(ix + 1, iy + 1, seed)
    return (a + (b - a) * fx + (c - a) * fy + (a - b - c + d) * fx * fy) * 2 - 1


def fbm_np(x, y, wavelengths_m, seed=0.0):
    """Unnormalized fbm: sum_k gain^k * value_noise(p / wavelength_k), each octave with its own hash seed."""
    s = np.zeros(np.broadcast(x, y).shape)
    for k, wl in enumerate(wavelengths_m):
        s += OCTAVE_GAIN ** k * value_noise_np(np.asarray(x) / wl, np.asarray(y) / wl, seed + 13.0 * (k + 1))
    return s


def fbm_std(wavelengths_m, seed=0.0, extent_m=4000.0, n=400_000, rng_seed=0):
    rng = np.random.default_rng(rng_seed)
    x, y = rng.uniform(-extent_m / 2, extent_m / 2, (2, n))
    return float(fbm_np(x, y, wavelengths_m, seed).std())


def _f(v):
    """MDL float literal (always with a '.' or an exponent: '2800f' is not valid MDL)."""
    s = f"{float(v):.7g}"
    return (s if ("." in s or "e" in s) else s + ".0") + "f"


def mdl_text(name="RegolithBombed", cell_m=1.0, tex_period_m=2.0, bump=0.8, albedo_brightness=0.6, ao_to_diffuse=0.35,
             bright_amp=0.2, bright_wavelengths_m=(48.0, 23.0, 11.0, 5.3), offset_xy=(0.0, 0.0), seed=0.0,
             fbm_norm=None):
    """MDL 1.6 source of the material `name` (relative texture paths: write it into OmniLRS assets/Textures/)."""
    if fbm_norm is None:
        fbm_norm = 0.5 / fbm_std(bright_wavelengths_m, seed) if bright_amp > 0 else 0.0
    octaves = "\n".join(
        f"    s += {_f(OCTAVE_GAIN ** k)} * vnoise(p / {_f(wl)}, seed + {_f(13.0 * (k + 1))});"
        for k, wl in enumerate(bright_wavelengths_m))
    dm = ", ".join(_f(v) for v in DIFF_MEAN_LIN)
    return f"""mdl 1.6;

import ::math::*;
import ::state::*;
import ::tex::*;
import ::df::*;

// generated by slam-benching sim/omnilrs/regolith_mdl.py: world-space texture bombing of LunarRegolith8k
// (cell {cell_m} m, texture period {tex_period_m} m, random rotation + offset per lattice point, variance-preserving
// blend) and world-space fbm albedo variation (amp {bright_amp}, wavelengths {list(bright_wavelengths_m)} m)

float hash1(float2 c, float seed)
{{
    float2 w = c - {_f(WRAP)} * math::floor(c / {_f(WRAP)});
    return math::frac(math::sin(w.x * 127.1f + w.y * 311.7f + seed * 74.7f) * 43758.5453f);
}}

float vnoise(float2 p, float seed)
{{
    float2 i = math::floor(p);
    float2 f = p - i;
    f = f * f * (3.0f - 2.0f * f);
    float a = hash1(i, seed);
    float b = hash1(i + float2(1.0f, 0.0f), seed);
    float c = hash1(i + float2(0.0f, 1.0f), seed);
    float d = hash1(i + float2(1.0f, 1.0f), seed);
    return (a + (b - a) * f.x + (c - a) * f.y + (a - b - c + d) * f.x * f.y) * 2.0f - 1.0f;
}}

float brightness(float2 p, float amp, float norm, float seed)
{{
    float s = 0.0f;
{octaves}
    return 1.0f + math::clamp(amp * norm * s, -1.5f * amp, 1.5f * amp);
}}

struct bomb_sample
{{
    float3 diff;
    float2 nxy;
    float ao;
}};

bomb_sample bomb(float2 p, float cell, float tex_scale, float seed, float3 dmean, float aomean,
                 uniform texture_2d dtex, uniform texture_2d ntex, uniform texture_2d atex)
{{
    float2 g = p / cell - 0.5f;
    float2 g0 = math::floor(g);
    float2 f = g - g0;
    f = f * f * (3.0f - 2.0f * f);
    float3 dsum = float3(0.0f);
    float2 nsum = float2(0.0f);
    float asum = 0.0f;
    float w2 = 0.0f;
    for (int j = 0; j < 2; ++j) {{
        for (int i = 0; i < 2; ++i) {{
            float2 c = g0 + float2(float(i), float(j));
            float w = (i == 0 ? 1.0f - f.x : f.x) * (j == 0 ? 1.0f - f.y : f.y);
            float ang = hash1(c, seed + 1.0f) * 6.2831853f;
            float2 o = float2(hash1(c, seed + 2.0f), hash1(c, seed + 3.0f));
            float ca = math::cos(ang);
            float sa = math::sin(ang);
            // texture coordinates relative to the lattice point keep float precision far from the origin
            float2 q = (p - (c + 0.5f) * cell) * tex_scale;
            float2 uv = float2(ca * q.x - sa * q.y, sa * q.x + ca * q.y) + o;
            float3 d = tex::lookup_float3(dtex, uv);
            float3 n = tex::lookup_float3(ntex, uv) * 2.0f - 1.0f;
            float ao = tex::lookup_float(atex, uv);
            dsum += w * (d - dmean);
            nsum += w * float2(ca * n.x + sa * n.y, -sa * n.x + ca * n.y);
            asum += w * (ao - aomean);
            w2 += w * w;
        }}
    }}
    float k = 1.0f / math::sqrt(math::max(w2, 1e-6f));
    return bomb_sample(dmean + dsum * k, nsum * k, aomean + asum * k);
}}

export material {name}(
    uniform texture_2d diffuse_texture = texture_2d("{TEX_DIR}/LunarRegolith8k_diff.png", ::tex::gamma_srgb),
    uniform texture_2d normal_texture = texture_2d("{TEX_DIR}/LunarRegolith8k_nor_gl.png", ::tex::gamma_linear),
    uniform texture_2d ao_texture = texture_2d("{TEX_DIR}/LunarRegolith8k_ao.png", ::tex::gamma_linear),
    float cell_m = {_f(cell_m)},
    float tex_period_m = {_f(tex_period_m)},
    float bump = {_f(bump)},
    float albedo_brightness = {_f(albedo_brightness)},
    float ao_to_diffuse = {_f(ao_to_diffuse)},
    float bright_amp = {_f(bright_amp)},
    float bright_norm = {_f(fbm_norm)},
    float2 offset_xy = float2({_f(offset_xy[0])}, {_f(offset_xy[1])}),
    float seed = {_f(seed)}
)
= let {{
    float3 pw = state::transform_point(state::coordinate_internal, state::coordinate_world, state::position());
    float2 p = float2(pw.x, pw.y) + offset_xy;
    bomb_sample s = bomb(p, cell_m, 1.0f / tex_period_m, seed, float3({dm}), {_f(AO_MEAN)},
                         diffuse_texture, normal_texture, ao_texture);
    float m = brightness(p, bright_amp, bright_norm, seed);
    float aof = math::lerp(1.0f, math::clamp(s.ao, 0.0f, 1.0f), ao_to_diffuse);
    color alb = color(math::clamp(s.diff, float3(0.0f), float3(1.0f)) * (albedo_brightness * m * aof));
    float3 N = state::normal();
    float3 ex = state::transform_vector(state::coordinate_world, state::coordinate_internal, float3(1.0f, 0.0f, 0.0f));
    float3 T = math::normalize(ex - N * math::dot(N, ex));
    float3 B = math::cross(N, T);
    float3 nrm = math::normalize(N + bump * (T * s.nxy.x + B * s.nxy.y));
}} in material(
    surface: material_surface(scattering: df::diffuse_reflection_bsdf(tint: alb)),
    geometry: material_geometry(normal: nrm)
);
"""
